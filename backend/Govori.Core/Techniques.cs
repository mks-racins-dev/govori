    private static readonly Dictionary<string, Technique> ById = All.ToDictionary(t => t.Id);

    public static Technique? Find(string? id) => id is null ? null : ById.GetValueOrDefault(id.Trim());

    /// <summary>The technique, only if it exists and belongs to the given criterion.</summary>
    public static Technique? ForCriterion(string? id, string criterion) =>
        Find(id) is { } t && t.Criterion == criterion ? t : null;

    /// <summary>The catalog as text for the system prompt, grouped by criterion.</summary>
    public static string Catalog()
    {
        var titles = new Dictionary<string, string>
        {
            ["thought"] = "Главная мысль (thought)",
            ["support"] = "Довод и пример (support)",
            ["conclusion"] = "Вывод (conclusion)",
            ["coherence"] = "Цельность (coherence)",
            ["delivery"] = "Подача (delivery) — выбирает приложение, тебе только для упражнения",
            [Vocabulary] = "Словарь (vocabulary) — для drill",
        };
        var sb = new StringBuilder();
        foreach (var group in All.GroupBy(t => t.Criterion))
        {
            sb.Append("### ").AppendLine(titles[group.Key]);
            foreach (var t in group)
                sb.Append("- ").Append(t.Id).Append(" — ").Append(t.Name).Append(". Формула: ").Append(t.Formula)
                  .Append(" Когда: ").Append(t.When).AppendLine(".");
            sb.AppendLine();
        }
        return sb.ToString().TrimEnd();
    }
